    val fallback: Phrase = SafePhraseFallback.phrase

    val phrases: List<Phrase> by lazy {
        buildList {
        addCategory("ground", PhraseCategory.NONJUDGMENT, grounding)
        addCategory("reset", PhraseCategory.REDIRECT, reset)
        addCategory("patience", PhraseCategory.IMPERMANENCE, patience)
        addCategory("choice", PhraseCategory.AUTONOMY, choice)
        addCategory("separation", PhraseCategory.SEPARATION, separation)
        }
    }

    fun resolve(id: PhraseId): Phrase = phrases.firstOrNull { it.id == id } ?: fallback

    fun resolve(candidate: Phrase): Phrase = candidate.takeIf {
        it.safetyReviewed && ContentPolicy.violations(it.text).isEmpty()
    } ?: fallback

    private fun MutableList<Phrase>.addCategory(
        prefix: String,
        category: PhraseCategory,
        copy: List<String>,
    ) {
        copy.forEachIndexed { index, text ->
            val intensityValue = index % 5 + 1
            add(
                Phrase(
                    id = PhraseId("$prefix-${(index + 1).toString().padStart(3, '0')}"),
                    text = text,
                    category = category,
                    tone = when (intensityValue) {
                        1, 2 -> PhraseTone.GENTLE
                        3 -> PhraseTone.NEUTRAL
                        else -> PhraseTone.FIRM
                    },
                    intensities = setOf(checkNotNull(Intensity.from(intensityValue))),
                    safetyReviewed = true,
                ),
            )
        }
    }

